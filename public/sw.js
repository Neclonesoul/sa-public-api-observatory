const CACHE = "sa-api-observatory-v1";
const SHELL = ["/", "/catalogue", "/infrastructure", "/ecosystem", "/methodology", "/catalogue.json", "/manifest.webmanifest"];
self.addEventListener("install", (event) => event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL))));
self.addEventListener("activate", (event) => event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))));
self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  event.respondWith(fetch(event.request).then((response) => {
    const copy = response.clone();
    caches.open(CACHE).then((cache) => cache.put(event.request, copy));
    return response;
  }).catch(() => caches.match(event.request).then((cached) => cached || new Response("OFFLINE — no cached observation is available for this request.", { status: 503, headers: { "Content-Type": "text/plain" } }))));
});
